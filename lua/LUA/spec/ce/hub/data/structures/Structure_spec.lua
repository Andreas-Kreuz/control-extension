insulate("ce.hub.data.structures.Structure", function ()
    local function clearModule(name) package.loaded[name] = nil end

    before_each(function ()
        clearModule("ce.hub.data.structures.Structure")
        clearModule("ce.hub.data.structures.StructureRegistry")
    end)

    it("stores values through setters and tracks dirty fields", function ()
        local Structure = require("ce.hub.data.structures.Structure")

        local structure = Structure:new("#3", "#3_Ampelmast")
        structure:setPosition(1.11, 2.22, 3.33)
        structure:setRotation(4.44, 5.55, 6.67)
        structure:setModelType(22, "Immobilie")
        structure:setTag("Depot")
        structure:setLight(true)
        structure:setSmoke(false)
        structure:setFire(true)

        assert.same("#3", structure.id)
        assert.same("#3_Ampelmast", structure.name)
        assert.same(1.11, structure:getPosX())
        assert.same(2.22, structure:getPosY())
        assert.same(3.33, structure:getPosZ())
        assert.same(4.44, structure:getRotX())
        assert.same(5.55, structure:getRotY())
        assert.same(6.67, structure:getRotZ())
        assert.same(22, structure:getModelType())
        assert.same("Immobilie", structure:getModelTypeText())
        assert.same("Depot", structure:getTag())
        assert.is_true(structure:getLight())
        assert.is_false(structure:getSmoke())
        assert.is_true(structure:getFire())
        assert.is_true(structure:hasDirtyFields())

        structure:resetDirty()
        structure:setPosition(1.11, 2.22, 3.33)
        structure:setRotation(4.44, 5.55, 6.67)
        structure:setModelType(22, "Immobilie")
        structure:setTag("Depot")
        structure:setLight(true)
        structure:setSmoke(false)
        structure:setFire(true)
        assert.is_false(structure:hasDirtyFields())
    end)

    it("remote setters update EEP and mark registry structures dirty", function ()
        local setPositionStub = stub(_G, "EEPStructureSetPosition", function () return true end)
        local setRotationStub = stub(_G, "EEPStructureSetRotation", function () return true end)
        local setLightStub = stub(_G, "EEPStructureSetLight", function () return true end)
        local setTagTextStub = stub(_G, "EEPStructureSetTagText", function () return true end)

        local Structure = require("ce.hub.data.structures.Structure")
        local StructureRegistry = require("ce.hub.data.structures.StructureRegistry")
        local structure = Structure:new("#3", "#3_Ampelmast")
        StructureRegistry.add(structure)
        structure:resetDirty()

        assert.is_true(Structure.setPositionByName("#3", "10.5", "20.25", "3.75"))
        assert.is_true(Structure.setRotationByName("#3", "1", "2", "90"))
        assert.is_true(Structure.setLightByName("#3", true))
        assert.is_true(Structure.setTagTextByName("#3", "F1=#4,"))

        assert.stub(setPositionStub).was_called_with("#3", 10.5, 20.25, 3.75)
        assert.stub(setRotationStub).was_called_with("#3", 1, 2, 90)
        assert.stub(setLightStub).was_called_with("#3", true)
        assert.stub(setTagTextStub).was_called_with("#3", "F1=#4,")
        assert.same(10.5, structure:getPosX())
        assert.same(20.25, structure:getPosY())
        assert.same(3.75, structure:getPosZ())
        assert.same(1, structure:getRotX())
        assert.same(2, structure:getRotY())
        assert.same(90, structure:getRotZ())
        assert.is_true(structure:getLight())
        assert.same("F1=#4,", structure:getTag())
        assert.is_true(structure:hasDirtyFields())

        setPositionStub:revert()
        setRotationStub:revert()
        setLightStub:revert()
        setTagTextStub:revert()
    end)

    it("remote setters find registry structures by full EEP name", function ()
        local setTagTextStub = stub(_G, "EEPStructureSetTagText", function () return true end)

        local Structure = require("ce.hub.data.structures.Structure")
        local StructureRegistry = require("ce.hub.data.structures.StructureRegistry")
        local structure = Structure:new("#3", "#3_Ampelmast")
        StructureRegistry.add(structure)
        structure:resetDirty()

        assert.is_true(Structure.setTagTextByName("#3_Ampelmast", "p1=#4,"))

        assert.stub(setTagTextStub).was_called_with("#3_Ampelmast", "p1=#4,")
        assert.same("p1=#4,", structure:getTag())
        assert.is_true(structure:hasDirtyFields())

        setTagTextStub:revert()
    end)
end)
